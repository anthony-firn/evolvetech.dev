"""Prepare Cloudflare Pages assets without changing the Bunny/Netlify source tree.

Cloudflare project: build command `python3 tools/build_cloudflare.py`, output `.cloudflare/public`.
Large WASM files are gzip encoded at their existing URLs. Custom encoding headers make browsers decode them.
"""
import argparse
import gzip
import hashlib
import json
import shutil
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIMIT = 25 * 1024 * 1024
MARKER = '.evolve-cloudflare-build.json'


def headers_for_cloudflare(text):
    """Pages joins matching header values; explicit detaches preserve the site's last-rule overrides."""
    lines = []
    for line in text.splitlines():
        stripped = line.strip()
        if line[:1].isspace() and ':' in stripped and not stripped.startswith(('#', '!')):
            name = stripped.split(':', 1)[0]
            lines.append(f'  ! {name}')
        lines.append(line)
    return '\n'.join(lines).rstrip() + '\n'


def build(source, output, limit=LIMIT):
    source, output = source.resolve(), output.resolve()
    if not source.is_dir() or source == output or output.is_relative_to(source) or source.is_relative_to(output):
        raise ValueError('Source and output must be separate, non-nested directories.')
    if output.exists() and not (output / MARKER).is_file():
        raise ValueError(f'Refusing to replace an unmanaged output directory: {output}')
    output.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix='.cloudflare-stage-', dir=output.parent))
    encoded = []
    try:
        for path in sorted(source.rglob('*')):
            if path.is_symlink():
                raise ValueError(f'Refusing symlink in deploy assets: {path.relative_to(source)}')
            if not path.is_file():
                continue
            relative = path.relative_to(source)
            target = staging / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            if path.stat().st_size > limit:
                if path.suffix != '.wasm':
                    raise ValueError(f'{relative} exceeds the Pages asset limit; move or split it explicitly.')
                original = path.read_bytes()
                compressed = gzip.compress(original, compresslevel=9, mtime=0)
                if len(compressed) > limit:
                    raise ValueError(f'{relative} still exceeds the Pages limit after gzip.')
                target.write_bytes(compressed)
                encoded.append({'path': '/' + relative.as_posix(), 'originalBytes': len(original),
                                'encodedBytes': len(compressed), 'decodedSha256': hashlib.sha256(original).hexdigest()})
            else:
                shutil.copy2(path, target)
        headers = staging / '_headers'
        text = headers_for_cloudflare(headers.read_text() if headers.exists() else '')
        for asset in encoded:
            text += (f"\n{asset['path']}\n  ! Content-Encoding\n  Content-Encoding: gzip\n"
                     "  ! Content-Type\n  Content-Type: application/wasm\n")
        headers.write_text(text)
        (staging / MARKER).write_text(json.dumps({'version': 1, 'encodedAssets': encoded}, indent=2) + '\n')
        if output.exists():
            # This directory is exclusively generated by this helper, as checked above.
            shutil.rmtree(output)
        staging.rename(output)
    finally:
        if staging.exists():
            shutil.rmtree(staging)
    return encoded


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--source', type=Path, default=ROOT / 'public')
    ap.add_argument('--output', type=Path, default=ROOT / '.cloudflare/public')
    args = ap.parse_args()
    encoded = build(args.source, args.output)
    print(f'Cloudflare assets ready: {args.output}')
    for a in encoded:
        print(f"{a['path']}: {a['originalBytes']:,} → {a['encodedBytes']:,} bytes; gzip with original URL")


if __name__ == '__main__':
    main()
